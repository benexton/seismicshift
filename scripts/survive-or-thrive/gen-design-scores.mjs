// Writes the SQL that (re)fills survive_or_thrive_design_scores - the
// server-side lookup the leaderboard uses to score a submission from its
// design, so the browser never gets to say what its own score is.
//
// Every valid design is enumerated straight from the game's own model
// (public/survive-or-thrive/model.js), so this table can't drift from what
// the game shows as long as it's regenerated after any scoring change:
//
//   node scripts/survive-or-thrive/gen-design-scores.mjs > design_scores.sql
//
// then run that file in the Supabase SQL editor for the survive-or-thrive
// project (qrblhtyoslxvoyyafgkl). It's idempotent - it replaces the whole
// table in one transaction.
import { readFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import vm from 'node:vm'

const modelPath = fileURLToPath(new URL('../../public/survive-or-thrive/model.js', import.meta.url))
const ctx = {}
vm.runInNewContext(readFileSync(modelPath, 'utf8'), ctx)
const M = ctx.SOT_MODEL

const rows = []
for (const typeKey of M.TYPE_ORDER) {
  for (const design of M.enumerate(typeKey)) {
    const r = M.evaluate(design)
    rows.push(`  ('${r.key}', ${r.score})`)
  }
}

process.stdout.write(`-- Generated by scripts/survive-or-thrive/gen-design-scores.mjs on ${new Date().toISOString().slice(0, 10)}.
-- Do not edit by hand - regenerate from the game's model instead.
-- ${rows.length} valid designs (score 0 = the design fails, so it can't be submitted).
begin;
delete from public.survive_or_thrive_design_scores;
insert into public.survive_or_thrive_design_scores (design_key, score) values
${rows.join(',\n')};
commit;
`)
